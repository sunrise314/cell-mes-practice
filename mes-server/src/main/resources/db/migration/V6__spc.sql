CREATE TABLE spc_chart (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT        NOT NULL,
    device_code      VARCHAR(64)   NOT NULL,
    process_id       INT           NOT NULL,
    characteristic   VARCHAR(32)   NOT NULL,   -- 容量 / 厚度 / 张力 ...
    subgroup_size    INT           NOT NULL DEFAULT 1,
    spec_lower       DECIMAL(12,4),            -- 规格下限 SL（外部约束）
    spec_upper       DECIMAL(12,4),            -- 规格上限 SU
    target           DECIMAL(12,4),            -- 规格中心 T
    control_lower    DECIMAL(12,4),            -- 控制下限 LCL（±3σ，内部统计，动态）
    control_upper    DECIMAL(12,4),            -- 控制上限 UCL
    mean_value       DECIMAL(12,4),            -- 当前基线均值 x̄
    sigma_value      DECIMAL(12,4),            -- 当前基线标准差 σ
    cp               DECIMAL(8,4),
    cpk              DECIMAL(8,4),
    ppk              DECIMAL(8,4),
    baseline_status  VARCHAR(16)   NOT NULL DEFAULT 'BASELINE_INIT',
                     -- BASELINE_INIT / ACTIVE / RECALCULATING（期间不软报警）
    baseline_since   TIMESTAMP,
    enabled_rules    JSONB         NOT NULL DEFAULT '["rule1","rule2","rule3","rule4","rule5","rule6","rule7","rule8"]',
    created_at       TIMESTAMP     NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, device_code, characteristic)
);

CREATE TABLE spc_sample (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT        NOT NULL,
    chart_id     BIGINT        NOT NULL,
    sample_time  TIMESTAMP     NOT NULL,
    subgroup_no  INT           NOT NULL,
    sample_value DECIMAL(12,4) NOT NULL,
    lot_id       BIGINT,                   -- 关联批次（规则违反时自动 hold）
    UNIQUE (tenant_id, chart_id, subgroup_no)
);
CREATE INDEX idx_spc_sample_chart ON spc_sample (chart_id, subgroup_no DESC);

-- 基线归档（ch08 落地清单 7：事故复盘可回放当时用的基线）
CREATE TABLE baseline_history (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT        NOT NULL,
    chart_id      BIGINT        NOT NULL,
    mean_value    DECIMAL(12,4),
    sigma_value   DECIMAL(12,4),
    control_lower DECIMAL(12,4),
    control_upper DECIMAL(12,4),
    archived_at   TIMESTAMP     NOT NULL DEFAULT now(),
    archive_reason VARCHAR(64)  NOT NULL DEFAULT 'RECALC'  -- RECALC / PARAM_CHANGE
);
