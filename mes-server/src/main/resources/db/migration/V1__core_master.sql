-- V1: 核心主数据（租户 / 物料 / ISA-95 设备层级 / 设备配方 / 库存）
-- 对应章节：ch01（ISA-95 层级）、ch02（多租户行级隔离）、ch05（Item.capacity_spec）
-- 说明：文章 DDL 为教学简化版，本工程在所有业务表上补齐 tenant_id（ch03 纪律）。
-- =====================================================================

-- 租户表：全局表，租户拦截器 ignoreTable 白名单内
CREATE TABLE tenant (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(32)  NOT NULL UNIQUE,
    name        VARCHAR(128) NOT NULL,
    status      VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at  TIMESTAMP    NOT NULL DEFAULT now()
);

-- 物料主数据（成品 / 原料统一）；capacity_spec 是 ch05 化成曲线双向校验的关键字段
CREATE TABLE item (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT       NOT NULL,
    code          VARCHAR(64)  NOT NULL,
    name          VARCHAR(128) NOT NULL,
    item_type     VARCHAR(16)  NOT NULL,            -- PRODUCT / MATERIAL
    capacity_spec VARCHAR(32),                      -- 280Ah / 314Ah（产品用）
    created_at    TIMESTAMP    NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, code)
);

-- ISA-95：Area → WorkCenter（工序级设备组）→ WorkCell（具体设备，派工只能到这一级）
CREATE TABLE work_center (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT       NOT NULL,
    code      VARCHAR(64)  NOT NULL,
    name      VARCHAR(128) NOT NULL,
    area      VARCHAR(64)  NOT NULL,               -- 极片车间/装配车间/化成车间
    UNIQUE (tenant_id, code)
);

CREATE TABLE work_cell (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      BIGINT       NOT NULL,
    code           VARCHAR(64)  NOT NULL,
    name           VARCHAR(128) NOT NULL,
    work_center_id BIGINT       NOT NULL,
    model          VARCHAR(64),                      -- 设备型号（化成曲线下发校验用）
    status         VARCHAR(16)  NOT NULL DEFAULT 'IDLE',
    UNIQUE (tenant_id, code)
);

-- 设备组（ch05 routing_operation.resource_group_id → 本表；device_codes 为可互替设备清单）
CREATE TABLE resource_group (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT       NOT NULL,
    code         VARCHAR(64)  NOT NULL,
    name         VARCHAR(128) NOT NULL,
    device_codes JSONB        NOT NULL,             -- ["BC-001","BC-002"]
    UNIQUE (tenant_id, code)
);

-- 设备配方（化成曲线等）；capacity_spec 与 item.capacity_spec 相等才允许下发（ch05 第 1.7/4 步）
CREATE TABLE device_recipe (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT       NOT NULL,
    code          VARCHAR(64)  NOT NULL,             -- FORN-280-CHG-V3
    capacity_spec VARCHAR(32)  NOT NULL,
    device_models JSONB        NOT NULL,             -- ["F1-96G"]
    params        JSONB,
    status        VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    UNIQUE (tenant_id, code)
);

-- 库存（ch05 改派前置校验 1.6：子料库存充足性）
CREATE TABLE inventory (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT          NOT NULL,
    item_id   BIGINT          NOT NULL,
    quantity  DECIMAL(14,4)   NOT NULL DEFAULT 0,
    UNIQUE (tenant_id, item_id)
);
