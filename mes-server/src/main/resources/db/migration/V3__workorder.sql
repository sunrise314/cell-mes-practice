-- =====================================================================
-- V3: 三件套实例层 —— WorkOrder / WorkOrderOperation / WorkOrderBomLine
-- 对应章节：ch01（dispatch_order 派工单实例）+ ch05（work_order_bom_line / work_order_operation）
-- 命名说明：ch01 的 dispatch_order ≡ 本表的 work_order_operation（按工序一行），
--           携带 work_cell_code / shift / planned_* / param_set_version 等派工字段。
-- =====================================================================

CREATE TABLE work_order (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT       NOT NULL,
    wo_no            VARCHAR(64)  NOT NULL,          -- WO-20251215-018
    product_item_id  BIGINT       NOT NULL,
    quantity         INT          NOT NULL,
    routing_id       BIGINT,
    bom_header_id    BIGINT,
    target_device_code VARCHAR(64),                  -- 目标设备（化成柜等，可空=由排程选择）
    status           VARCHAR(16)  NOT NULL DEFAULT 'CREATED',
                     -- CREATED/RELEASED/STARTED/PAUSED/COMPLETED/CLOSED
    created_at       TIMESTAMP    NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, wo_no)
);

CREATE TABLE work_order_operation (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id             BIGINT          NOT NULL,
    wo_no                 VARCHAR(64)     NOT NULL,
    seq                   INT             NOT NULL,
    operation_name        VARCHAR(64)     NOT NULL,
    resource_group_id     BIGINT,
    work_cell_code        VARCHAR(64),                -- 派工只到 WorkCell 级（ch01 关键约束）
    shift_date            DATE,
    shift_code            VARCHAR(8),                 -- A/B/C 三班
    planned_start         TIMESTAMP,
    planned_end           TIMESTAMP,
    standard_duration_min DECIMAL(8,2),
    process_params        JSONB,
    param_set_version     INT,                        -- 防止改派时参数错配（ch01/ch03）
    status                VARCHAR(16) NOT NULL DEFAULT 'WAITING',
                          -- WAITING / ISSUED（已发料）/ RUNNING / DONE
    UNIQUE (tenant_id, wo_no, seq)
);

CREATE TABLE work_order_bom_line (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT        NOT NULL,
    wo_no         VARCHAR(64)   NOT NULL,
    line_no       INT           NOT NULL,
    child_item_id BIGINT        NOT NULL,
    quantity      DECIMAL(14,4) NOT NULL,             -- 单颗用量 × 工单数量
    unit          VARCHAR(16)   NOT NULL,
    operation_seq INT,
    substitutes   JSONB,
    status        VARCHAR(16)   NOT NULL DEFAULT 'PENDING',  -- PENDING / ISSUED
    UNIQUE (tenant_id, wo_no, line_no)
);
