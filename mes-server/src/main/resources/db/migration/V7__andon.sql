CREATE TABLE andon_call (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id             BIGINT       NOT NULL,
    call_time             TIMESTAMP    NOT NULL DEFAULT now(),
    call_source           VARCHAR(16)  NOT NULL,   -- MANUAL/DEVICE/SPC/CUSTOMER/AI_PREDICTION
    call_level            VARCHAR(4)   NOT NULL,   -- L1/L2/L3/L4
    device_code           VARCHAR(64),
    process_id            INT,
    lot_id                BIGINT,
    caller_id             BIGINT,
    title                 VARCHAR(128) NOT NULL,
    description           TEXT,
    status                VARCHAR(16)  NOT NULL DEFAULT 'OPEN',
                          -- OPEN / RESPONDING / RESOLVED / CLOSED
    sla_response_min      INT          NOT NULL,
    sla_onsite_min        INT          NOT NULL,
    sla_response_deadline TIMESTAMP,
    sla_onsite_deadline   TIMESTAMP,
    responded_at          TIMESTAMP,
    resolved_at           TIMESTAMP,
    closed_at             TIMESTAMP,
    assignee_id           BIGINT,
    escalate_to_id        BIGINT,
    escalate_count        INT          NOT NULL DEFAULT 0,
    eight_d_case_id       BIGINT
);
-- ch09：定时扫描 OPEN 状态 + SLA 截止
CREATE INDEX idx_andon_status ON andon_call (status, sla_response_deadline);

CREATE TABLE eight_d_case (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id            BIGINT       NOT NULL,
    title                VARCHAR(128) NOT NULL,
    open_time            TIMESTAMP    NOT NULL DEFAULT now(),
    status               VARCHAR(16)  NOT NULL DEFAULT 'OPEN',   -- OPEN/CLOSED
    current_step         VARCHAR(4)   NOT NULL DEFAULT 'D1',     -- D1-D8（状态机不可跳步）
    -- D1 团队
    team_lead_id         BIGINT,
    team_members         JSONB,                -- [{"user_id":1,"role":"质量"},...]
    -- D2 问题描述（5W2H）
    problem_desc         TEXT,
    problem_5w2h         JSONB,
    -- D3 临时措施
    interim_actions      TEXT,
    interim_actions_time TIMESTAMP,
    -- D4 根因
    root_cause           TEXT,
    root_cause_method    VARCHAR(32),          -- 5WHY / FISHBONE / FMEA
    -- D5 永久措施
    permanent_actions    TEXT,
    -- D6 验证
    verification_result  TEXT,
    -- D7 防止再发生
    prevention_actions   TEXT,
    -- D8 表彰
    recognition          TEXT,
    close_time           TIMESTAMP,
    andon_call_id        BIGINT NOT NULL,
    UNIQUE (andon_call_id)
);
