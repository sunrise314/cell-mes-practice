-- SCADA 原始状态 → 时间类别映射（每工序独立配置，禁用全局统一映射）
CREATE TABLE status_mapping (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT       NOT NULL,
    process_id    INT          NOT NULL,      -- 1涂布 2辊压 3分切 4卷绕 5注液 6化成 7分容
    scada_status  VARCHAR(32)  NOT NULL,      -- RUN/IDLE/PM/CHG/MAT_WAIT/ALARM/MECH/ELEC/OFF
    time_category VARCHAR(32)  NOT NULL,
                  -- run_time / idle_time / planned_down / unplanned_down
    UNIQUE (tenant_id, process_id, scada_status)
);

-- 班次日历：OEE 总时间按日历累加，节假日 is_holiday=true 直接从分母排除
CREATE TABLE shift_calendar (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT      NOT NULL,
    shift_date  DATE        NOT NULL,
    shift_code  VARCHAR(8)  NOT NULL,       -- A/B/C/OFF
    start_time  TIMESTAMP   NOT NULL,       -- 24:00 归 C 班开始（开始时间归属原则）
    end_time    TIMESTAMP   NOT NULL,
    crew_id     BIGINT,                     -- 班组；未排班不算总时间
    is_holiday  BOOLEAN     NOT NULL DEFAULT FALSE,
    UNIQUE (tenant_id, shift_date, shift_code)
);

-- 秒级状态按 1 分钟聚合（取众数），OEE 计算只读分钟表（禁用秒级算 OEE）
CREATE TABLE scada_status_minute (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT         NOT NULL,
    device_code   VARCHAR(64)    NOT NULL,
    process_id    INT            NOT NULL,
    shift_date    DATE           NOT NULL,
    shift_code    VARCHAR(8)     NOT NULL,
    minute_ts     TIMESTAMP      NOT NULL,
    scada_status  VARCHAR(32)    NOT NULL,
    actual_output INT            NOT NULL DEFAULT 0,
    reject_qty    INT            NOT NULL DEFAULT 0,
    standard_rate DECIMAL(10,4)  NOT NULL DEFAULT 0,   -- 标准产出：件/分钟
    UNIQUE (tenant_id, device_code, minute_ts)
);
CREATE INDEX idx_ssm_device_date ON scada_status_minute (tenant_id, device_code, shift_date);

-- 停机事件：原因大类→中类→小类三层编码，每个非计划停机必须填到 level3
CREATE TABLE downtime_event (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      BIGINT       NOT NULL,
    device_code    VARCHAR(64)  NOT NULL,
    start_time     TIMESTAMP    NOT NULL,
    end_time       TIMESTAMP,
    duration_min   INT          NOT NULL,
    reason_level1  VARCHAR(32)  NOT NULL,   -- 设备故障/待料/报警/人员
    reason_level2  VARCHAR(32),             -- 机械/电气/上工序缺料/...
    reason_level3  VARCHAR(64),             -- 具体原因描述
    operator_id    BIGINT,
    shift_code     VARCHAR(8)
);
