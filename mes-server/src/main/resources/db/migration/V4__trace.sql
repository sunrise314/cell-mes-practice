-- =====================================================================
-- V4: 批次追溯三链 —— Lot / MaterialMovement / 召回规则 / 替代料日志
-- 对应章节：ch06（批次三链、双向链表、CTE 递归、RecallRule 规则引擎）
-- 说明：文章 DDL 的 device_id BIGINT 在本工程落地为 device_code VARCHAR（WorkCell 编码），
--       operation_id BIGINT 落地为 operation_seq INT（1涂布 2辊压 3分切 4卷绕 5注液 6化成 7分容）。
-- =====================================================================

CREATE TABLE lot (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT          NOT NULL,
    lot_no     VARCHAR(64)     NOT NULL,
    lot_type   VARCHAR(16)     NOT NULL,
               -- POWDER/COIL/SUBCOIL/BARE_CELL/FILLED_CELL/FORMED_CELL/FINAL_CELL/MATERIAL
    item_id    BIGINT,
    quantity   DECIMAL(14,4)   NOT NULL DEFAULT 0,
    unit       VARCHAR(16),
    status     VARCHAR(16)     NOT NULL DEFAULT 'IN_STOCK',
               -- IN_STOCK / CONSUMED / SHIPPED / HOLD（ch08/ch09/ch10 自动 hold 目标）
    created_at TIMESTAMP       NOT NULL DEFAULT now()
);
-- 同一 SN 贯穿注液后各阶段（FILLED/FORMED/FINAL 同 lot_no 不同 lot_type），按三元组唯一
CREATE UNIQUE INDEX uk_lot_tenant_no_type ON lot (tenant_id, lot_no, lot_type);

-- 物料移动：一表记录料链/工序链/设备链三条链（ch06 批次三链）
CREATE TABLE material_movement (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT        NOT NULL,
    event_time       TIMESTAMP     NOT NULL,
    -- 料链：上游批次强制扫描（from_lot_id 非空 = 追溯链物理上不可能断）
    from_lot_id      BIGINT        NOT NULL,
    from_lot_type    VARCHAR(16),
    -- 工序链
    work_order_id    BIGINT,
    operation_seq    INT           NOT NULL,
    -- 设备链
    device_code      VARCHAR(64)   NOT NULL,
    -- 产出
    to_lot_id        BIGINT,
    to_lot_type      VARCHAR(16),
    quantity         DECIMAL(14,4),
    unit             VARCHAR(16),
    -- 双向链表（递归追溯的入口；1→N 分叉场景 CTE 走 lot 关联，见 TraceDao）
    prev_movement_id BIGINT,
    next_movement_id BIGINT
);

-- ch06 落地清单：三个索引必建
CREATE INDEX idx_mm_from_lot ON material_movement (tenant_id, from_lot_id);
CREATE INDEX idx_mm_to_lot   ON material_movement (tenant_id, to_lot_id);
CREATE INDEX idx_mm_wo_op    ON material_movement (tenant_id, work_order_id, operation_seq);

-- 召回规则元数据（运营可加规则不改代码；bean 名 = Spring Bean key）
CREATE TABLE recall_rule_config (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT       NOT NULL,
    rule_name   VARCHAR(64)  NOT NULL,      -- samePowderLot / sameElectrolyteLot / sameFormationCurve
    rule_bean   VARCHAR(64)  NOT NULL,
    description VARCHAR(256),
    enabled     BOOLEAN      NOT NULL DEFAULT TRUE,
    UNIQUE (tenant_id, rule_name)
);

-- 替代料选择日志（ch05：合规审计要求，记录选择过程与理由）
CREATE TABLE substitution_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      BIGINT       NOT NULL,
    wo_no          VARCHAR(64)  NOT NULL,
    bom_line_id    BIGINT,
    main_item_id   BIGINT       NOT NULL,
    chosen_item_id BIGINT       NOT NULL,
    priority       INT,
    reason         VARCHAR(256),
    created_at     TIMESTAMP    NOT NULL DEFAULT now()
);
