-- =====================================================================
-- V2: 三件套模板层 —— Routing / RoutingOperation / BomHeader / BomLine
-- 对应章节：ch01（routing/routing_operation/bom）、ch05（bom_header/bom_line、替代料 substitutes JSONB）
-- =====================================================================

CREATE TABLE routing (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT       NOT NULL,
    product_item_id BIGINT       NOT NULL,
    revision        VARCHAR(32)  NOT NULL,           -- V3
    status          VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',  -- ACTIVE / DEPRECATED
    UNIQUE (tenant_id, product_item_id, revision)
);

CREATE TABLE routing_operation (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id             BIGINT          NOT NULL,
    routing_id            BIGINT          NOT NULL,
    seq                   INT             NOT NULL,     -- 工序号 1-7（DAG 前置关系按 seq 排序近似）
    operation_code        VARCHAR(32)     NOT NULL,     -- COAT/ROLL/SLIT/WIND/FILL/FORM/TEST
    operation_name        VARCHAR(64)     NOT NULL,
    work_center_code      VARCHAR(64),                  -- ch01 默认工作中心
    resource_group_id     BIGINT,                       -- ch05 可用设备组
    standard_duration_min DECIMAL(8,2)    NOT NULL,     -- 参考批量 1000 颗的整段节拍（分钟）
    process_params        JSONB,                        -- {"formation_curve":"FORN-280-CHG-V3"}
    critical_param_set    VARCHAR(64),                  -- ch01 关键参数集（SPC 基线重置事件来源）
    UNIQUE (tenant_id, routing_id, seq)
);

CREATE TABLE bom_header (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT      NOT NULL,
    product_item_id BIGINT      NOT NULL,
    revision        VARCHAR(32) NOT NULL,
    effective_from  DATE        NOT NULL,
    effective_to    DATE,
    status          VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',  -- ACTIVE / DEPRECATED
    UNIQUE (tenant_id, product_item_id, revision)
);

CREATE TABLE bom_line (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT         NOT NULL,
    bom_header_id BIGINT         NOT NULL,
    line_no       INT            NOT NULL,
    child_item_id BIGINT         NOT NULL,
    quantity      DECIMAL(12,4)  NOT NULL,            -- 单颗用量
    unit          VARCHAR(16)    NOT NULL,            -- kg / g / pcs / m
    operation_seq INT,                                -- 投入工序 seq（ch01：BOM 行必须绑工序）
    substitutes   JSONB,                              -- [{"item_id":123,"priority":1}]（ch05）
    UNIQUE (tenant_id, bom_header_id, line_no)
);
