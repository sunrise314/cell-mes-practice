CREATE TABLE model_version (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT       NOT NULL,
    version          VARCHAR(16)  NOT NULL,    -- v1.0.0
    model_path       VARCHAR(256) NOT NULL,    -- 规则版为配置标识
    mae              DECIMAL(8,4),
    r2               DECIMAL(8,4),
    accuracy         DECIMAL(8,4),
    false_alarm_rate DECIMAL(8,4),
    miss_rate        DECIMAL(8,4),
    status           VARCHAR(16)  NOT NULL DEFAULT 'EXPERIMENT',
                     -- EXPERIMENT / STAGING / PRODUCTION / RETIRED
    created_at       TIMESTAMP    NOT NULL DEFAULT now(),
    promoted_at      TIMESTAMP,
    UNIQUE (tenant_id, version)
);

CREATE TABLE capacity_prediction (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         BIGINT        NOT NULL,
    lot_id            BIGINT        NOT NULL,
    device_code       VARCHAR(64)   NOT NULL,
    predicted_capacity DECIMAL(12,4) NOT NULL,
    features          JSONB,
    action            VARCHAR(16)   NOT NULL,  -- PASS / WARN / HOLD
    predicted_at      TIMESTAMP     NOT NULL DEFAULT now()
);
CREATE INDEX idx_cp_lot ON capacity_prediction (tenant_id, lot_id);
